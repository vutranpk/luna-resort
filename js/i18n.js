function setLanguage(lang) {
    // Update UI buttons
    const btnEn = document.getElementById('btn-lang-en');
    const btnVi = document.getElementById('btn-lang-vi');
    
    if (lang === 'en') {
        btnEn.className = 'lang-active transition-colors pb-1';
        btnVi.className = 'lang-inactive transition-colors pb-1';
    } else {
        btnVi.className = 'lang-active transition-colors pb-1';
        btnEn.className = 'lang-inactive transition-colors pb-1';
    }

    // Update all translated elements
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (i18n[lang] && i18n[lang][key]) {
            el.innerHTML = i18n[lang][key];
        }
    });
}

// Initialize with English as default
document.addEventListener('DOMContentLoaded', () => {
    setLanguage('en');
});
